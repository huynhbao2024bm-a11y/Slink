'use strict';
const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs/promises');
const path = require('node:path');
const { randomUUID } = require('node:crypto');
const { buildServer } = require('../index');
const { createPGlitePool } = require('../pglite-test-pool');
const origin = 'http://slink.test';

async function setup(t) {
  const { PGlite } = await import('@electric-sql/pglite');
  const db = new PGlite();
  const directory = path.join(__dirname, '..', 'migrations');
  for (const name of (await fs.readdir(directory)).filter(name => name.endsWith('.sql')).sort()) await db.exec(await fs.readFile(path.join(directory, name), 'utf8'));
  await db.exec('CREATE ROLE slink_app NOLOGIN; GRANT USAGE ON SCHEMA public TO slink_app; GRANT SELECT, INSERT, UPDATE, DELETE ON ALL TABLES IN SCHEMA public TO slink_app; GRANT USAGE, SELECT ON ALL SEQUENCES IN SCHEMA public TO slink_app;');
  const app = await buildServer({ pool: createPGlitePool(db), logger: false, env: { NODE_ENV: 'test', PUBLIC_ORIGIN: origin } });
  t.after(() => app.close());
  const email = randomUUID() + '@example.test', password = 'a sufficiently long test password 47';
  const registered = await app.inject({ method: 'POST', url: '/api/auth/register', headers: { origin }, payload: { email, password, displayName: 'Người thử', storeName: 'Cửa hàng offline thử' } });
  assert.equal(registered.statusCode, 201, registered.body);
  const token = new URLSearchParams(new URL(registered.json().developmentVerificationUrl).hash.slice(1)).get('token');
  await app.inject({ method: 'POST', url: '/api/auth/verify-email', headers: { origin }, payload: { token } });
  const login = await app.inject({ method: 'POST', url: '/api/auth/login', headers: { origin }, payload: { email, password } });
  assert.equal(login.statusCode, 200, login.body);
  const cookies = Object.fromEntries(login.headers['set-cookie'].map(value => { const [pair] = value.split(';'), i = pair.indexOf('='); return [pair.slice(0, i), pair.slice(i + 1)]; }));
  const headers = { origin, cookie: Object.entries(cookies).map(([k, v]) => k + '=' + v).join('; '), 'x-csrf-token': cookies.slink_csrf };
  const storeId = login.json().stores[0].id, base = '/api/stores/' + storeId;
  const send = (tail, payload, key = randomUUID()) => app.inject({ method: 'POST', url: base + tail, headers: { ...headers, 'idempotency-key': key }, payload });
  const get = tail => app.inject({ method: 'GET', url: base + tail, headers });
  const product = await send('/products/import', { items: [{ name: 'Mặt hàng offline', sku: 'OFF-1', salePriceVnd: 80000, costVnd: 10000, openingQuantity: '12' }] });
  assert.equal(product.statusCode, 201, product.body);
  const catalog = (await get('/products?limit=100')).json();
  const warehouseId = (await get('/warehouses?view=picker')).json().warehouses.find(w => w.is_default).id;
  return { app, db, send, get, storeId, productId: catalog.products[0].id, warehouseId };
}

test('offline operations preserve business time, replay once and reconcile a cash shift atomically', async t => {
  const { db, send, get, productId, warehouseId } = await setup(t);
  const baseTime = Date.now() - 86400000, deviceId = randomUUID();
  const metadata = (minutes, cashSessionId = null, expectedCashVnd = null) => ({ deviceId, occurredAt: new Date(baseTime + minutes * 60000).toISOString(), cashSessionId, expectedCashVnd });
  const opened = await send('/cash-register/open', { openingFloatVnd: '100000', offline: metadata(0) });
  assert.equal(opened.statusCode, 201, opened.body); const sessionId = opened.json().session.id;
  const sale = { warehouseId, items: [{ productId, quantity: 1, expectedUnitPriceVnd: '80000' }], totalVnd: '80000', amountReceivedVnd: '100000', method: 'cash', offline: metadata(1, sessionId) };
  const key = randomUUID(), sold = await send('/sales', sale, key);
  assert.equal(sold.statusCode, 201, sold.body);
  const replay = await send('/sales', sale, key);
  assert.equal(replay.statusCode, 201, replay.body); assert.equal(replay.headers['idempotent-replayed'], 'true');
  assert.equal(replay.json().order.id, sold.json().order.id);
  const product = (await get('/products?limit=100')).json().products[0];
  const purchase = await send('/purchases', { warehouseId, items: [{ productId, quantity: 5, unitCostVnd: 10000, expectedProductVersion: product.version }], amountPaidVnd: 50000, method: 'cash', offline: metadata(2, sessionId) });
  assert.equal(purchase.statusCode, 201, purchase.body);
  const after = (await get('/products?limit=100')).json().products[0];
  const counted = await send('/stock-adjustments', { warehouseId, productId, count: 15, expectedInventoryVersion: after.inventory_version, reason: 'Kiểm kê thực tế', offline: metadata(3) });
  assert.equal(counted.statusCode, 201, counted.body);
  const expense = await send('/cash-movements', { direction: 'out', category: 'Vận hành', amountVnd: 10000, method: 'cash', offline: metadata(4, sessionId) });
  assert.equal(expense.statusCode, 201, expense.body);
  const closed = await send('/cash-register/' + sessionId + '/close', { countedCashVnd: '120000', offline: metadata(5, sessionId, '120000') });
  assert.equal(closed.statusCode, 201, closed.body); assert.equal(closed.json().session.varianceVnd, '0');
  assert.equal((await get('/products?limit=100')).json().products[0].on_hand, '15.000');
  const timestamps = await db.query('SELECT occurred_at FROM orders WHERE id=$1', [sold.json().order.id]);
  assert.equal(new Date(timestamps.rows[0].occurred_at).toISOString(), metadata(1).occurredAt);
  const receipts = await db.query('SELECT kind, client_occurred_at, received_at FROM offline_operation_receipts ORDER BY client_occurred_at');
  assert.equal(receipts.rows.length, 6);
  assert.ok(receipts.rows.every(row => new Date(row.received_at) - new Date(row.client_occurred_at) > 23 * 3600000));
  const cashDates = await db.query("SELECT occurred_at FROM cash_movements WHERE source_type IN ('order_payment','order_change')");
  assert.ok(cashDates.rows.every(row => new Date(row.occurred_at).toISOString() === metadata(1).occurredAt));
  const normal = await send('/cash-register/open', { openingFloatVnd: 0 });
  assert.equal(normal.statusCode, 201, normal.body);
  assert.ok(Date.now() - new Date(normal.json().session.openedAt).getTime() < 10000, 'offline time never leaks into a later normal transaction');
  await assert.rejects(() => db.query("UPDATE offline_operation_receipts SET kind='cash'"), /append-only/);
});

test('offline price, cash-session and count conflicts reject without partial money or stock writes', async t => {
  const { db, send, get, productId, warehouseId } = await setup(t);
  const opened = await send('/cash-register/open', { openingFloatVnd: 100000 }); const sessionId = opened.json().session.id;
  const metadata = { deviceId: randomUUID(), occurredAt: new Date().toISOString(), cashSessionId: sessionId, expectedCashVnd: null };
  const sale = { warehouseId, items: [{ productId, quantity: 1, expectedUnitPriceVnd: '79000' }], totalVnd: 79000, amountReceivedVnd: 79000, offline: metadata };
  const mismatch = await send('/sales', sale);
  assert.equal(mismatch.statusCode, 409, mismatch.body); assert.equal(mismatch.json().error.code, 'offline_price_changed');
  sale.items[0].expectedUnitPriceVnd = '80000'; sale.totalVnd = 80000; sale.amountReceivedVnd = 80000; sale.offline.cashSessionId = randomUUID();
  const wrongShift = await send('/sales', sale);
  assert.equal(wrongShift.statusCode, 409, wrongShift.body); assert.equal(wrongShift.json().error.code, 'offline_cash_session_changed');
  const cashConflict = await send('/cash-register/' + sessionId + '/close', { countedCashVnd: 100000, offline: { ...metadata, cashSessionId: sessionId, expectedCashVnd: '99999' } });
  assert.equal(cashConflict.statusCode, 409, cashConflict.body); assert.equal(cashConflict.json().error.code, 'offline_cash_balance_changed');
  const countConflict = await send('/stock-adjustments', { warehouseId, productId, count: 10, expectedInventoryVersion: 999, offline: metadata });
  assert.equal(countConflict.statusCode, 409, countConflict.body);
  const wrongActor = await send('/cash-movements', { direction: 'in', category: 'Vận hành', amountVnd: 1000, method: 'cash', offline: { ...metadata, cashSessionId: sessionId, actorUserId: randomUUID() } });
  assert.equal(wrongActor.statusCode, 403, wrongActor.body); assert.equal(wrongActor.json().error.code, 'offline_identity_changed');
  const row = (await get('/products?limit=100')).json().products[0]; assert.equal(row.on_hand, '12.000');
  assert.equal((await get('/cash-register')).json().session.expectedCashVnd, '100000');
  assert.equal((await db.query('SELECT count(*)::int AS n FROM orders')).rows[0].n, 0);
  assert.equal((await db.query('SELECT count(*)::int AS n FROM offline_operation_receipts')).rows[0].n, 0);
});
